#!/usr/bin/env python3
"""Generate ir_codes.h (scan lists) from Flipper Zero universal remote files.

Usage:
  B=https://raw.githubusercontent.com/flipperdevices/flipperzero-firmware/dev/applications/main/infrared/resources/infrared/assets
  curl -LO $B/tv.ir -LO $B/ac.ir
  python3 tools/gen_ir_codes.py tv.ir Power "TV power" ac.ir Off "AC off" > ir_codes.h

Arguments are triples: file, button name, list title.
Parsed codes are converted to IRremoteESP8266 data values
(same as the library encode* functions), raw ones are kept as timings.
"""
import sys


def rev8(b):
    return int('{:08b}'.format(b & 0xFF)[::-1], 2)


def rev(v, n):
    return int('{:0{}b}'.format(v, n)[::-1], 2)


def nec_bytes(bs):
    return (rev8(bs[0]) << 24) | (rev8(bs[1]) << 16) | (rev8(bs[2]) << 8) | rev8(bs[3])


def le(field):
    bs = [int(x, 16) for x in field.split()]
    return bs, bs[0] | (bs[1] << 8) | (bs[2] << 16) | (bs[3] << 24)


def parsed(proto, addr_field, cmd_field):
    """Returns (type, code, bits) or None if unsupported."""
    ab, a = le(addr_field)
    cb, c = le(cmd_field)
    if proto == 'NEC':
        return 'NEC', nec_bytes([a, ~a, c, ~c]), 32
    if proto == 'NECext':
        return 'NEC', nec_bytes([ab[0], ab[1], cb[0], cb[1]]), 32
    if proto == 'Samsung32':
        return 'SAMSUNG', nec_bytes([a, a, c, ~c]), 32
    if proto == 'RC5':
        code = ((a & 0x1F) << 6) | (c & 0x3F)
        if c < 64:
            return 'RC5', code, 12
        return 'RC5X', (((c >> 6) & 1) << 12) | code, 13
    if proto == 'RC6':
        return 'RC6', ((a & 0xFFF) << 8) | (c & 0xFF), 20
    if proto == 'SIRC':
        return 'SONY', rev(((a & 0x1F) << 7) | (c & 0x7F), 12), 12
    if proto == 'SIRC15':
        return 'SONY', rev(((a & 0xFF) << 7) | (c & 0x7F), 15), 15
    return None


def blocks(path):
    """Yields entries; each gets the preceding '# Model:' comment as 'model'."""
    entry, model = {}, ''
    for line in open(path):
        line = line.strip()
        if line.startswith('#'):
            if entry:
                entry['model'] = model
                yield entry
            entry = {}
            if line.startswith('# Model:'):
                model = line[len('# Model:'):].strip()
        elif ':' in line:
            k, v = line.split(':', 1)
            entry[k.strip()] = v.strip()
    if entry:
        entry['model'] = model
        yield entry


def c_str(text):
    return '"%s"' % text.replace('\\', '\\\\').replace('"', '\\"')


def main(args):
    raws, lists, raw_max = [], [], 0
    for li in range(0, len(args), 3):
        path, button, title = args[li:li + 3]
        entries = []
        for e in blocks(path):
            if e.get('name') != button:
                continue
            model = e['model'][:40]
            if e.get('type') == 'parsed':
                p = parsed(e['protocol'], e['address'], e['command'])
                if p is None:
                    print('skipped unsupported protocol %s' % e['protocol'], file=sys.stderr)
                    continue
                entries.append('  {decode_type_t::%s, %d, 0x%X, nullptr, 0, %s},' % (p[0], p[2], p[1], c_str(model)))
            elif e.get('type') == 'raw':
                # Timings over 65535us are pauses between repeats; shortening them is harmless.
                data = [min(int(x), 0xFFFF) for x in e['data'].split()]
                raw_max = max(raw_max, len(data))
                name = 'raw%d' % len(raws)
                raws.append('static const uint16_t %s[] PROGMEM = {%s};' % (name, ', '.join(map(str, data))))
                entries.append('  {decode_type_t::RAW, %d, 0, %s, %d, %s},' % (int(e['frequency']) // 1000, name, len(data), c_str(model)))
        lists.append((title, entries))

    print('/* Generated by tools/gen_ir_codes.py from Flipper Zero universal remote files. Do not edit. */')
    print('#ifndef IR_CODES_H\n#define IR_CODES_H\n')
    print('#include <IRremoteESP8266.h>\n')
    print('#define IR_CODES_RAW_MAX %d\n' % raw_max)
    print('/* For RAW entries bits holds the carrier frequency in kHz. */')
    print('typedef struct {\n  decode_type_t type;\n  uint8_t bits;\n  uint32_t code;\n  const uint16_t* raw;\n  uint16_t rawLen;\n  char model[41];\n} ir_code_t;\n')
    print('typedef struct {\n  const char* title;\n  const ir_code_t* codes;\n  uint16_t count;\n} ir_code_list_t;\n')
    print('\n'.join(raws))
    for i, (title, entries) in enumerate(lists):
        print('\nstatic const ir_code_t irCodes%d[] PROGMEM = {' % i)
        print('\n'.join(entries))
        print('};')
    print('\nstatic const ir_code_list_t irCodeLists[] = {')
    for i, (title, entries) in enumerate(lists):
        print('  {%s, irCodes%d, %d},' % (c_str(title), i, len(entries)))
    print('};\n\n#endif')


if __name__ == '__main__':
    main(sys.argv[1:])
